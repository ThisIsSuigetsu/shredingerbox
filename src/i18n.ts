// Язык интерфейса. Тексты пишутся по-русски прямо в коде, а t() подставляет английский
// перевод из словаря EN. Нет перевода - остаётся русский (в режиме разработки - с предупреждением).

export type Lang = "ru" | "en";
export type LangSetting = "system" | Lang;

let lang: Lang = "ru";

export const getLang = () => lang;
export const locale = () => (lang === "en" ? "en-US" : "ru-RU");

export function setLang(l: Lang) {
  lang = l;
  document.documentElement.lang = l;
}

/** «Как в системе»: русский для русской, белорусской и казахской системы, иначе английский. */
export function resolveLang(setting: LangSetting): Lang {
  if (setting === "ru" || setting === "en") return setting;
  const sys = (navigator.languages?.[0] ?? navigator.language ?? "en").toLowerCase();
  return /^(ru|be|kk)\b/.test(sys) ? "ru" : "en";
}

/** Перевод строки. {name} в тексте заменяется значением из vars. */
export function t(ru: string, vars?: Record<string, string | number>): string {
  let s = ru;
  if (lang === "en") {
    const en = EN[ru];
    if (en !== undefined) s = en;
    else if (import.meta.env.DEV) console.warn("[i18n] нет перевода:", ru);
  }
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

